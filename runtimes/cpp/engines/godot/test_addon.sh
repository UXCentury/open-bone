#!/usr/bin/env bash
# Checks an assembled addon on its own: makes a fresh Godot project that contains only addons/openbone (copied from
# ADDON_ROOT) and one .obone document with the images it references, imports it headless, then instantiates
# OpenBoneSprite, loads the document, advances a few frames and prints a bone transform. Also instantiates a saved scene
# whose OpenBoneSprite has Document set in the Inspector, which must load on its own when the node enters the tree.
#
#   test_addon.sh ADDON_ROOT GODOT DOCUMENT.obone [BONE] [WORK_DIR]
#
# ADDON_ROOT: the OUT_DIR given to package.sh (holds addons/openbone). GODOT: a Godot 4.4+ editor binary.
# Exits non-zero when the extension doesn't load or the document doesn't play.
set -euo pipefail

if [ $# -lt 3 ]; then
  echo "usage: test_addon.sh ADDON_ROOT GODOT DOCUMENT.obone [BONE] [WORK_DIR]" >&2
  exit 2
fi
root="$(cd "$1" && pwd)" godot="$2" doc="$3" bone="${4:-}" work="${5:-}"
[ -f "$root/addons/openbone/openbone.gdextension" ] || { echo "no addons/openbone in $root" >&2; exit 2; }
[ -n "$work" ] || work="$(mktemp -d)"
rm -rf "$work" && mkdir -p "$work"
proj="$work/project"
mkdir -p "$proj"

cp -R "$root/addons" "$proj/"
name="$(basename "$doc")"
cp "$doc" "$proj/$name"
# Images and sounds the document references by relative path ("src": "assets/…").
docdir="$(cd "$(dirname "$doc")" && pwd)"
grep -o '"src" *: *"[^"]*"' "$doc" | sed 's/.*: *"\(.*\)"/\1/' | grep -v '^data:' | sort -u | while IFS= read -r src; do
  [ -f "$docdir/$src" ] || continue
  mkdir -p "$proj/$(dirname "$src")"
  cp "$docdir/$src" "$proj/$src"
done

cat > "$proj/project.godot" <<'EOF'
; Generated by runtimes/cpp/engines/godot/test_addon.sh
config_version=5

[application]

config/name="OpenBone addon check"
EOF

# A scene with Document set as a property, the way the Inspector saves it (loaded in _ready, not by load()).
cat > "$proj/scene.tscn" <<EOF
[gd_scene format=3]

[node name="Sprite" type="OpenBoneSprite"]
document = "res://$name"
EOF

cat > "$proj/check.gd" <<'EOF'
extends SceneTree
## Loads a document with OpenBoneSprite from the installed addon and prints one bone's transform.

func _initialize() -> void:
	var args := OS.get_cmdline_user_args()
	var path: String = args[0]
	var bone: String = args[1] if args.size() > 1 else ""
	if not ClassDB.class_exists("OpenBoneSprite"):
		printerr("FAIL: OpenBoneSprite is not registered (addon not loaded)")
		quit(1)
		return
	var sprite = ClassDB.instantiate("OpenBoneSprite")
	root.add_child(sprite)
	if not sprite.load(path):
		printerr("FAIL: could not load ", path)
		quit(1)
		return
	var anims: PackedStringArray = sprite.get_animations()
	if anims.is_empty():
		printerr("FAIL: no animations in ", path)
		quit(1)
		return
	sprite.play(anims[0], true)
	for i in 10:
		sprite.advance(1.0 / 60.0)
	if bone == "":
		bone = "root"
	var items: Array = sprite.get_draw_items()
	print("OpenBone addon ", Engine.get_version_info().string, ": ", path.get_file(), " animation ", anims[0], " after 10 frames: bone ", bone, " = ", sprite.get_bone_transform(bone), ", ", items.size(), " draw items")
	if items.is_empty():
		printerr("FAIL: nothing to draw")
		quit(1)
		return
	# Document set in a saved scene (the Inspector's way) loads when the node enters the tree.
	var scene: Node = load("res://scene.tscn").instantiate()
	root.add_child(scene)
	await process_frame
	if scene.get_draw_items().is_empty() or scene.document != path:
		printerr("FAIL: a scene's Document property didn't load (document = '", scene.document, "')")
		quit(1)
		return
	print("OK")
	quit(0)
EOF

# A fresh project has to be imported once before Godot loads its GDExtensions (and its textures).
# Its exit status isn't trusted: the check below is what counts (some editor builds crash on shutdown after importing).
"$godot" --headless --path "$proj" --import >"$work/import.log" 2>&1 || echo "warning: godot --import exited with $? (log: $work/import.log)"
out="$("$godot" --headless --path "$proj" -s check.gd -- "res://$name" "$bone" 2>&1)" || { echo "$out"; exit 1; }
echo "$out"
echo "$out" | grep -q '^OK$'
