/** Unity editor script: slices the sheet from `<name>.unity.json` and builds one AnimationClip per clip. */
export const UNITY_IMPORTER_CS = `// OpenBone sprite sheet importer for Unity (2021.3+). MIT licensed, generated by OpenBone.
// Select a *.unity.json file and choose Assets > OpenBone > Import Sprite Sheet.
#if UNITY_EDITOR
using System.Collections.Generic;
using System.IO;
using UnityEditor;
using UnityEngine;

namespace OpenBone.EditorTools
{
    public static class OpenBoneSpriteSheetImporter
    {
        [System.Serializable] class SheetData { public string image; public int width; public int height; }
        [System.Serializable] class FrameData { public string name; public int sheet; public int x; public int y; public int width; public int height; public float pivotX; public float pivotY; public string alias; }
        [System.Serializable] class ClipData { public string name; public float fps; public bool loop; public string[] frames; }
        [System.Serializable] class PackData { public string generator; public int version; public float pixelsPerUnit; public SheetData[] sheets; public FrameData[] frames; public ClipData[] clips; }

        const string Menu = "Assets/OpenBone/Import Sprite Sheet";

        [MenuItem(Menu, true)]
        static bool CanImport()
        {
            var path = Selection.activeObject != null ? AssetDatabase.GetAssetPath(Selection.activeObject) : "";
            return path.EndsWith(".unity.json");
        }

        [MenuItem(Menu)]
        static void ImportSelected() => Import(AssetDatabase.GetAssetPath(Selection.activeObject));

        /// <summary>Slice the sheets and create the clips for one exported pack (path relative to the project, e.g. "Assets/hero/hero.unity.json").</summary>
        public static void Import(string jsonPath)
        {
            var data = JsonUtility.FromJson<PackData>(File.ReadAllText(jsonPath));
            var dir = Path.GetDirectoryName(jsonPath).Replace('\\\\', '/');
            var sprites = new Dictionary<string, Sprite>();
            var byName = new Dictionary<string, FrameData>();
            foreach (var f in data.frames) byName[f.name] = f;

            for (int s = 0; s < data.sheets.Length; s++)
            {
                var texPath = dir + "/" + data.sheets[s].image;
                var importer = AssetImporter.GetAtPath(texPath) as TextureImporter;
                if (importer == null) { Debug.LogError("OpenBone: texture not found: " + texPath); return; }
                importer.textureType = TextureImporterType.Sprite;
                importer.spriteImportMode = SpriteImportMode.Multiple;
                importer.spritePixelsPerUnit = data.pixelsPerUnit > 0 ? data.pixelsPerUnit : 100;
                importer.textureCompression = TextureImporterCompression.Uncompressed;
                importer.mipmapEnabled = false;
                importer.alphaIsTransparency = true;
                importer.maxTextureSize = Mathf.Max(2048, Mathf.NextPowerOfTwo(Mathf.Max(data.sheets[s].width, data.sheets[s].height)));
                var metas = new List<SpriteMetaData>();
                foreach (var f in data.frames)
                {
                    if (f.sheet != s || !string.IsNullOrEmpty(f.alias)) continue;
                    metas.Add(new SpriteMetaData
                    {
                        name = f.name,
                        rect = new Rect(f.x, f.y, f.width, f.height),
                        alignment = (int)SpriteAlignment.Custom,
                        pivot = new Vector2(f.pivotX, f.pivotY),
                    });
                }
#pragma warning disable 618 // spritesheet is obsolete in Unity 6 but still works
                importer.spritesheet = metas.ToArray();
#pragma warning restore 618
                importer.SaveAndReimport();
                foreach (var asset in AssetDatabase.LoadAllAssetsAtPath(texPath))
                    if (asset is Sprite sprite) sprites[sprite.name] = sprite;
            }

            foreach (var clip in data.clips)
            {
                var fps = clip.fps > 0 ? clip.fps : 30f;
                var anim = new AnimationClip { frameRate = fps };
                var keys = new List<ObjectReferenceKeyframe>();
                for (int i = 0; i < clip.frames.Length; i++)
                {
                    var f = byName[clip.frames[i]];
                    var key = string.IsNullOrEmpty(f.alias) ? f.name : f.alias;
                    if (!sprites.TryGetValue(key, out var sprite)) { Debug.LogWarning("OpenBone: missing sprite " + key); continue; }
                    keys.Add(new ObjectReferenceKeyframe { time = i / fps, value = sprite });
                }
                if (keys.Count == 0) continue;
                // Hold the last frame for one frame so the clip length is frames / fps.
                keys.Add(new ObjectReferenceKeyframe { time = clip.frames.Length / fps, value = keys[keys.Count - 1].value });
                var binding = EditorCurveBinding.PPtrCurve("", typeof(SpriteRenderer), "m_Sprite");
                AnimationUtility.SetObjectReferenceCurve(anim, binding, keys.ToArray());
                var settings = AnimationUtility.GetAnimationClipSettings(anim);
                settings.loopTime = clip.loop;
                AnimationUtility.SetAnimationClipSettings(anim, settings);
                AssetDatabase.CreateAsset(anim, dir + "/" + clip.name + ".anim");
            }
            AssetDatabase.SaveAssets();
            Debug.Log("OpenBone: imported " + sprites.Count + " sprites and " + data.clips.Length + " clips from " + jsonPath);
        }
    }
}
#endif
`;

/** Flutter, no dependencies: load TexturePacker JSON (as written by OpenBone) and play a clip with a CustomPainter. */
export const FLUTTER_SHEET_DART = `// OpenBone sprite sheet player for Flutter. MIT licensed, generated by OpenBone.
// No packages needed. Reads the TexturePacker JSON (Hash) files exported by OpenBone.
import 'dart:convert';
import 'dart:ui' as ui;

import 'package:flutter/scheduler.dart';
import 'package:flutter/services.dart';
import 'package:flutter/widgets.dart';

/// One frame: where it is on its sheet and where the trimmed rect sits inside the full frame.
class OpenBoneFrame {
  const OpenBoneFrame(this.sheet, this.rect, this.offset);
  final int sheet;
  final Rect rect;
  final Offset offset;
}

class OpenBoneClip {
  const OpenBoneClip(this.name, this.fps, this.loop, this.frames);
  final String name;
  final double fps;
  final bool loop;
  final List<OpenBoneFrame> frames;

  Duration get duration => Duration(microseconds: (frames.length / fps * 1e6).round());
}

class OpenBoneSpriteSheet {
  OpenBoneSpriteSheet._(this.images, this.clips, this.sourceSize, this.origin);

  /// Sheet textures, by sheet index.
  final List<ui.Image> images;
  final Map<String, OpenBoneClip> clips;

  /// Full (untrimmed) frame size in pixels.
  final Size sourceSize;

  /// Skeleton origin inside the full frame, in pixels from the top-left.
  final Offset origin;

  /// Load the first sheet's JSON; further sheets are found through meta.related_multi_packs.
  static Future<OpenBoneSpriteSheet> load(String jsonAsset, {AssetBundle? bundle}) async {
    final assets = bundle ?? rootBundle;
    final dir = jsonAsset.substring(0, jsonAsset.lastIndexOf('/') + 1);
    final first = jsonDecode(await assets.loadString(jsonAsset)) as Map<String, dynamic>;
    final meta = first['meta'] as Map<String, dynamic>;
    final files = <String>[
      jsonAsset.substring(dir.length),
      ...((meta['related_multi_packs'] as List?)?.cast<String>() ?? const <String>[]),
    ];
    final images = <ui.Image>[];
    final frames = <String, OpenBoneFrame>{};
    for (var i = 0; i < files.length; i++) {
      final data = i == 0 ? first : jsonDecode(await assets.loadString(dir + files[i])) as Map<String, dynamic>;
      final image = (data['meta'] as Map<String, dynamic>)['image'] as String;
      images.add(await _loadImage(assets, dir + image));
      (data['frames'] as Map<String, dynamic>).forEach((name, value) {
        final f = value as Map<String, dynamic>;
        final r = f['frame'] as Map<String, dynamic>;
        final s = f['spriteSourceSize'] as Map<String, dynamic>;
        frames[name] = OpenBoneFrame(
          i,
          Rect.fromLTWH(_d(r['x']), _d(r['y']), _d(r['w']), _d(r['h'])),
          Offset(_d(s['x']), _d(s['y'])),
        );
      });
    }
    final ob = meta['openbone'] as Map<String, dynamic>;
    final size = ob['sourceSize'] as Map<String, dynamic>;
    final origin = ob['origin'] as Map<String, dynamic>;
    final clips = <String, OpenBoneClip>{};
    for (final c in (ob['clips'] as List).cast<Map<String, dynamic>>()) {
      final name = c['name'] as String;
      final count = c['frames'] as int;
      final list = [for (var n = 1; n <= count; n++) frames['\${name}_\${n.toString().padLeft(4, '0')}']!];
      clips[name] = OpenBoneClip(name, _d(c['fps']), c['loop'] as bool, list);
    }
    return OpenBoneSpriteSheet._(images, clips, Size(_d(size['w']), _d(size['h'])), Offset(_d(origin['x']), _d(origin['y'])));
  }

  /// The frame of [clip] shown at [time] seconds.
  OpenBoneFrame frameAt(OpenBoneClip clip, double time) {
    final n = clip.frames.length;
    var i = (time * clip.fps).floor();
    i = clip.loop ? i % n : i.clamp(0, n - 1);
    return clip.frames[i];
  }

  static double _d(Object? v) => (v as num).toDouble();

  static Future<ui.Image> _loadImage(AssetBundle assets, String path) async {
    final bytes = await assets.load(path);
    final codec = await ui.instantiateImageCodec(bytes.buffer.asUint8List(bytes.offsetInBytes, bytes.lengthInBytes));
    return (await codec.getNextFrame()).image;
  }
}

/// Plays one clip of a sheet, scaled to fit [width] x [height] (keeping aspect ratio).
class OpenBoneSpriteAnimation extends StatefulWidget {
  const OpenBoneSpriteAnimation({super.key, required this.sheet, required this.clip, this.width, this.height, this.playing = true});
  final OpenBoneSpriteSheet sheet;
  final String clip;
  final double? width;
  final double? height;
  final bool playing;

  @override
  State<OpenBoneSpriteAnimation> createState() => _OpenBoneSpriteAnimationState();
}

class _OpenBoneSpriteAnimationState extends State<OpenBoneSpriteAnimation> with SingleTickerProviderStateMixin {
  late final Ticker _ticker;
  Duration _elapsed = Duration.zero;

  @override
  void initState() {
    super.initState();
    _ticker = createTicker((d) => setState(() => _elapsed = d));
    if (widget.playing) _ticker.start();
  }

  @override
  void didUpdateWidget(OpenBoneSpriteAnimation old) {
    super.didUpdateWidget(old);
    if (old.clip != widget.clip) {
      _ticker.stop();
      _elapsed = Duration.zero;
    }
    if (widget.playing && !_ticker.isActive) _ticker.start();
    if (!widget.playing && _ticker.isActive) _ticker.stop();
  }

  @override
  void dispose() {
    _ticker.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final clip = widget.sheet.clips[widget.clip];
    if (clip == null) return const SizedBox.shrink();
    final frame = widget.sheet.frameAt(clip, _elapsed.inMicroseconds / 1e6);
    return SizedBox(
      width: widget.width,
      height: widget.height,
      child: CustomPaint(painter: _FramePainter(widget.sheet, frame)),
    );
  }
}

class _FramePainter extends CustomPainter {
  _FramePainter(this.sheet, this.frame);
  final OpenBoneSpriteSheet sheet;
  final OpenBoneFrame frame;

  @override
  void paint(Canvas canvas, Size size) {
    final src = sheet.sourceSize;
    final s = (size.width / src.width) < (size.height / src.height) ? size.width / src.width : size.height / src.height;
    final dx = (size.width - src.width * s) / 2;
    final dy = (size.height - src.height * s) / 2;
    final dst = Rect.fromLTWH(dx + frame.offset.dx * s, dy + frame.offset.dy * s, frame.rect.width * s, frame.rect.height * s);
    canvas.drawImageRect(sheet.images[frame.sheet], frame.rect, dst, Paint()..filterQuality = FilterQuality.medium);
  }

  @override
  bool shouldRepaint(_FramePainter old) => old.frame != frame || old.sheet != sheet;
}
`;

/** Flame component that plays an OpenBone sprite sheet clip, honouring trim offsets. */
export const FLAME_COMPONENT_DART = `// OpenBone sprite sheet component for Flame 1.x. MIT licensed, generated by OpenBone.
// Needs: flame in pubspec.yaml, and openbone_sprite_sheet.dart next to this file.
import 'dart:ui';

import 'package:flame/components.dart';

import 'openbone_sprite_sheet.dart';

/// Draws the current frame so the component's position is the skeleton origin.
class OpenBoneSpriteComponent extends PositionComponent {
  OpenBoneSpriteComponent(this.sheet, {required String clip, super.position, super.scale, super.priority})
      : _clip = sheet.clips[clip]!;

  final OpenBoneSpriteSheet sheet;
  final Paint _paint = Paint()..filterQuality = FilterQuality.medium;
  OpenBoneClip _clip;
  double _time = 0;
  bool playing = true;

  String get clip => _clip.name;

  /// Switch clip and restart it.
  void play(String clip) {
    _clip = sheet.clips[clip]!;
    _time = 0;
    playing = true;
  }

  /// True once a non-looping clip has shown its last frame.
  bool get finished => !_clip.loop && _time * _clip.fps >= _clip.frames.length;

  @override
  void update(double dt) {
    super.update(dt);
    if (playing) _time += dt;
  }

  @override
  void render(Canvas canvas) {
    final f = sheet.frameAt(_clip, _time);
    final dst = Rect.fromLTWH(f.offset.dx - sheet.origin.dx, f.offset.dy - sheet.origin.dy, f.rect.width, f.rect.height);
    canvas.drawImageRect(sheet.images[f.sheet], f.rect, dst, _paint);
  }
}
`;
